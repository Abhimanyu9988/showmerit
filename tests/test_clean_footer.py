import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "tools"))
import clean_footer

FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"

assert clean_footer.clean(f"text\n\n---\n{FOOTER}\n") == "text\n"
assert clean_footer.clean("a\n---\nb\n") == "a\n---\nb\n"
assert FOOTER in clean_footer.clean(f"see {FOOTER} here\n")
assert clean_footer.clean(None) == ""
print("footer tests passed")
